def test_stamp_statistics_flag_non_increasing_times():
    """Spacing stats are exact on a regular grid and the strict-increase flag trips on a repeat."""
    regular = compute_stamp_statistics(np.arange(5) * 0.1)
    assert regular["strictly_increasing"] is True
    assert regular["spacing_median"] == pytest.approx(0.1)
    broken = compute_stamp_statistics(np.array([0.0, 0.1, 0.1, 0.3]))
    assert broken["strictly_increasing"] is False
    assert broken["spacing_min"] == pytest.approx(0.0)


def test_lidar_discontinuity_flags_both_sides_of_a_depth_jump_only():
    """A flat wall with one 5 m step flags exactly the two points adjacent to the step."""
    azimuths = np.deg2rad(np.arange(0.0, 10.0, 0.2))
    ranges = np.where(azimuths < np.deg2rad(5.0), 10.0, 5.0)
    sweep = np.column_stack(
        [ranges * np.cos(azimuths), ranges * np.sin(azimuths), np.zeros_like(azimuths),
         np.ones_like(azimuths), np.arange(azimuths.size) * 1e-4, np.zeros_like(azimuths)]
    ).astype(np.float32)
    weights, _ = compute_lidar_discontinuity(sweep)
    flagged = np.flatnonzero(weights > 0)
    jump_index = int(np.flatnonzero(azimuths >= np.deg2rad(5.0))[0])
    assert flagged.tolist() == [jump_index - 1, jump_index]


