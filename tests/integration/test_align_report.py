def test_projection_matches_analytic_pixel():
    """p_world = T_wl p; p_cam = inv(T_wc) p_world; pixel = K p_cam / z (computed here by hand)."""
    time_seconds = 0.1
    world_point = np.array([5.0, 0.5, 0.2])
    pose_lidar, pose_camera = lidar_pose_world(time_seconds), camera_pose_world(time_seconds)
    # Lidar-frame coordinates of the world point: R^T (p - t).
    point_lidar = pose_lidar[:3, :3].T @ (world_point - pose_lidar[:3, 3])
    camera_matrix = np.array([[FOCAL_PIXELS, 0, PRINCIPAL_X], [0, FOCAL_PIXELS, PRINCIPAL_Y], [0, 0, 1.0]])
    pixels, in_front, inside = project_sweep_to_pixels(
        point_lidar[None, :], pose_lidar, pose_camera, camera_matrix, IMAGE_WIDTH, IMAGE_HEIGHT)
    camera_point = pose_camera[:3, :3].T @ (world_point - pose_camera[:3, 3])
    expected_u = FOCAL_PIXELS * camera_point[0] / camera_point[2] + PRINCIPAL_X
    expected_v = FOCAL_PIXELS * camera_point[1] / camera_point[2] + PRINCIPAL_Y
    assert in_front[0] and inside[0]
    assert pixels[0] == pytest.approx([expected_u, expected_v], abs=1e-6)


def test_aligned_scene_report_outputs_and_peak_at_zero(aligned_report):
    """Overlays/report files exist, inside counts are positive, the yaw score peaks at 0, verdict PASS."""
    report, base_directory = aligned_report
    output_directory = base_directory / "out"
    assert (output_directory / "report.md").is_file()
    assert (output_directory / "metrics.json").is_file()
    assert len(report["frames"]) == 3
    for frame in report["frames"]:
        assert (output_directory / frame["overlay_file"]).is_file()
        assert str(frame["lidar_frame_index"]).zfill(6) in frame["overlay_file"]
        assert frame["points_inside_image"] > 0
        assert 0.0 < frame["inside_fraction"] <= 1.0
        # The camera stamp is CAMERA_LATENCY after the lidar stamp.
        assert frame["camera_lidar_time_delta"] == pytest.approx(CAMERA_LATENCY, abs=1e-6)
    sweep = report["sensitivity"]
    # edge_alignment_score samples the gradient at the nearest pixel, so the argmax is only
    # defined to +-1 grid step (one pixel angle).
    assert abs(sweep["yaw_argmax_radians"]) <= PIXEL_ANGLE * (1 + 1e-9)
    scores = dict(zip(np.round(sweep["yaw_angles_radians"], 12), sweep["yaw_scores"]))
    zero_score = scores[0.0]
    # Clearly worse three or more pixels away (a sharp, correctly placed edge).
    for pixel_multiple in (3, 4, 6, 8):
        for sign in (-1, 1):
            assert scores[round(sign * pixel_multiple * PIXEL_ANGLE, 12)] < zero_score
    assert report["verdict"] == "PASS", report["verdict_reasons"]
    # Time statistics: vehicle moves VEHICLE_SPEED m/s for (FRAME_COUNT-1) sweeps.
    motion = report["motion"]
    assert motion["path_length"] == pytest.approx(VEHICLE_SPEED * SWEEP_PERIOD * (FRAME_COUNT - 1), rel=1e-6)
    assert motion["speed_p50"] == pytest.approx(VEHICLE_SPEED, rel=1e-6)
    assert report["time"]["lidar"]["strictly_increasing"] and report["time"]["camera"]["strictly_increasing"]


def test_miscalibrated_camera_recovers_yaw_and_warns(tmp_path):
    """Stored camera pose = true @ Ry(3 px): the sweep argmax is at -3 px and the verdict is WARN."""
    yaw_error_pixels = 3
    build_scene_dataset(tmp_path / "ds", camera_yaw_error_radians=yaw_error_pixels * PIXEL_ANGLE)
    report = generate_align_report(tmp_path / "ds", tmp_path / "out", requested_frames=3)
    # pose' = true Ry(e) Ry(phi) is aligned when phi = -e.
    assert report["sensitivity"]["yaw_argmax_radians"] == pytest.approx(
        -yaw_error_pixels * PIXEL_ANGLE, abs=1.01 * PIXEL_ANGLE)  # same +-1 step quantisation
    assert report["verdict"] == "WARN"
    assert (tmp_path / "out" / "report.md").read_text().count("WARN") >= 1


def test_script_runs_on_synthetic_config_and_fails_on_missing_dataset(tmp_path):
    """Script exit 0 with default-style --out on a valid dataset; exit 1 when the dataset is absent."""
    build_scene_dataset(tmp_path / "ds")
    config = {
        "session": {"name": "synthetic_scene", "extrinsics_variant": "x", "bag_dir": "b", "calibration_dir": "c",
                    "labels_json": "l", "labels_sample_key": "k", "output_dir": str(tmp_path / "ds"),
                    "gt_dir": "g"},
        "window": {}, "topics": {}, "frames": {}, "camera": {"name": "cam"}, "lidar": {"name": "lidar"},
        "radar": {}, "split": {}, "splatad": {},
    }
    config_path = tmp_path / "session.yaml"
    config_path.write_text(yaml.safe_dump(config))
    completed = subprocess.run(
        [sys.executable, str(ALIGN_SCRIPT), "--config", str(config_path), "--frames", "2",
         "--out", str(tmp_path / "out")], capture_output=True, text=True)
    assert completed.returncode == 0, completed.stderr
    assert (tmp_path / "out" / "report.md").is_file()
    config["session"]["output_dir"] = str(tmp_path / "missing")
    config_path.write_text(yaml.safe_dump(config))
    missing = subprocess.run(
        [sys.executable, str(ALIGN_SCRIPT), "--config", str(config_path), "--out", str(tmp_path / "out2")],
        capture_output=True, text=True)
    assert missing.returncode == 1


def test_texture_free_scene_is_inconclusive_not_warn(tmp_path):
    """A constant image has no gradient: every sweep is uninformative, verdict INCONCLUSIVE (never WARN)."""
    build_scene_dataset(tmp_path / "ds", texture_free=True)
    report = generate_align_report(tmp_path / "ds", tmp_path / "out", requested_frames=3)
    assert report["verdict"] == "INCONCLUSIVE"
    assert report["sensitivity"]["yaw_status"] == report["sensitivity"]["time_status"] == "INCONCLUSIVE"
    assert not report["sensitivity"]["yaw_informative"]
    assert "metric uninformative on this scene; rely on overlays" in (tmp_path / "out" / "report.md").read_text()


def test_time_sweep_extends_past_boundary_and_recovers_half_period_offset(tmp_path):
    """Camera content is really 0.5 period later than its stamp: the grid edge (+0.5) triggers the
    extension and the extended argmax stays at ~+0.5 (interior), not at the new boundary."""
    period_fraction = 0.5
    # 20 m/s lateral motion: half a period (0.05 s) moves the camera 1 m = ~40 px at the 5 m panel,
    # so the time shift is clearly observable in the vertical panel edges.
    build_scene_dataset(tmp_path / "ds", vehicle_speed=20.0, camera_time_offset=period_fraction * SWEEP_PERIOD,
                        frame_count=12)
    report = generate_align_report(tmp_path / "ds", tmp_path / "out", requested_frames=4)
    sweep = report["sensitivity"]
    assert sweep["time_extended"]
    assert max(sweep["time_shifts_frames"]) > 0.5  # grid really grew beyond +-0.5
    assert sweep["time_argmax_frames"] == pytest.approx(period_fraction, abs=0.25 + 1e-9)
    assert not sweep["time_boundary_peak"]
    assert sweep["time_informative"]


